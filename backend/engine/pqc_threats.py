"""Post-quantum era threats — the register that keeps working after migration.

WHY THIS EXISTS
---------------
Every product in this category treats post-quantum cryptography as a destination:
score the estate, rank the backlog, migrate to ML-KEM, done. That is wrong in a
way that will become obvious to customers around 2029, and it is the reason this
module exists.

**Migrating to a post-quantum algorithm does not end cryptographic risk. It
changes which risks apply.** Four of them are already documented:

  1. The new algorithms have **implementation** vulnerabilities. ML-KEM and
     ML-DSA are mathematically sound but their physical implementations leak;
     side-channel and fault attacks against masked implementations are an active
     research area with published results on real devices.
  2. The new algorithms have had **far less cryptanalysis** than RSA or ECC.
     Module lattices are a structured variant chosen for performance, and that
     structure is exactly what a future attack would exploit.
  3. **Harvest-now-decrypt-later is retroactive.** Traffic captured before
     migration stays captured. Migrating the endpoint does not un-capture it.
  4. **The threat model itself moves.** Between May 2025 and March 2026 published
     estimates of the quantum resources needed to factor RSA-2048 fell from
     ~20 million qubits to under 1 million. An engine with a fixed survival curve
     was wrong the day that work appeared and had no way to notice.

A tool that stops at "migrated: yes" cannot express any of this. This register
is deliberately the part of the product that has no end state.

DESIGN NOTES
------------
Every entry is a stated, sourced position with an explicit `status`, not a
severity score. These are conditions of the world, not properties of one estate;
`assess` maps them onto an estate to say which apply *here*.

Nothing in this module is generated by a model, and none of it is a prediction.
Where the position depends on ongoing research, `review_by` says when the claim
should be re-checked, because a register that is never revisited becomes
misinformation.
"""

