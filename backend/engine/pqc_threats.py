_BY_KEY = {t.key: t for t in THREATS}

STATUS_ORDER = {"active": 0, "emerging": 1, "monitored": 2}


def register() -> list[dict]:
    """The full register, most-settled evidence first."""
    return [
        {
            "key": t.key,
            "title": t.title,
            "status": t.status,
            "summary": t.summary,
            "applies_to": t.applies_to,
            "mitigation": t.mitigation,
            "evidence": t.evidence,
            "review_by": t.review_by,
            "review_overdue": t.review_by < date.today().isoformat(),
        }
        for t in sorted(THREATS, key=lambda t: (STATUS_ORDER.get(t.status, 9), t.title))
    ]


def assess(assets: list) -> dict:
    """Which post-quantum-era threats apply to this estate, and on what evidence.

    Deliberately conservative: an estate is only reported as exposed where a
    concrete, countable property of it triggers the threat. Nothing is asserted
    from the absence of data.
    """
    migrated = [a for a in assets if not getattr(a, "quantum_vulnerable", False)
                and getattr(a, "verdict", "") == "pqc"]
    hardware_bound = [
        a for a in assets
        if getattr(a, "asset_class", "") in {"payment_hsm", "firmware_signing", "device_identity"}
    ]
    long_retention = [a for a in assets if getattr(a, "x_c", 0) >= 8.0]
    hard_to_change = [
        a for a in assets
        if getattr(a, "agility_key", "") in {"hardware-bound", "vendor-blocked", "programme"}
    ]
    still_vulnerable = [a for a in assets if getattr(a, "quantum_vulnerable", False)]

    findings = []

    if migrated:
        findings.append({
            "threat": "pqc_side_channel",
            "exposed_count": len(migrated),
            "why": (
                f"{len(migrated)} asset(s) already use post-quantum algorithms. "
                "Their exposure is now an implementation property, not an "
                "algorithm property."
            ),
        })
        findings.append({
            "threat": "lattice_cryptanalysis_immaturity",
            "exposed_count": len(migrated),
            "why": (
                f"{len(migrated)} asset(s) depend on lattice assumptions that have "
                "had roughly a decade of scrutiny."
            ),
        })

    if hardware_bound:
        findings.append({
            "threat": "pqc_side_channel",
            "exposed_count": len(hardware_bound),
            "why": (
                f"{len(hardware_bound)} asset(s) are hardware-resident, which is "
                "where side-channel exposure is highest and remediation slowest."
            ),
        })

    if long_retention:
        findings.append({
            "threat": "retroactive_hndl",
            "exposed_count": len(long_retention),
            "why": (
                f"{len(long_retention)} asset(s) protect data with a "
                "confidentiality horizon of eight years or more. Anything already "
                "captured stays captured after migration."
            ),
        })

    if hard_to_change:
        findings.append({
            "threat": "agility_debt",
            "exposed_count": len(hard_to_change),
            "why": (
                f"{len(hard_to_change)} asset(s) cannot be changed by "
                "configuration, so the next algorithm transition costs as much as "
                "this one."
            ),
        })

    # Threat-model drift applies to every estate with a schedule, always.
    if assets:
        findings.append({
            "threat": "threat_model_drift",
            "exposed_count": len(still_vulnerable),
            "why": (
                f"{len(still_vulnerable)} asset(s) have deadlines computed against "
                "the current survival curve. Those dates move when the curve is "
                "re-fitted."
            ),
        })

    # Collapse duplicates, keeping the largest exposure per threat.
    merged: dict[str, dict] = {}
    for finding in findings:
        key = finding["threat"]
        if key not in merged or finding["exposed_count"] > merged[key]["exposed_count"]:
            merged[key] = finding

    applicable = []
    for key, finding in merged.items():
        threat = _BY_KEY[key]
        applicable.append({
            **finding,
            "title": threat.title,
            "status": threat.status,
            "mitigation": threat.mitigation,
        })

    applicable.sort(key=lambda f: (STATUS_ORDER.get(f["status"], 9), -f["exposed_count"]))

    return {
        "estate_size": len(assets),
        "already_post_quantum": len(migrated),
        "still_vulnerable": len(still_vulnerable),
        "applicable_threats": applicable,
        "register_size": len(THREATS),
        "note": (
            "These are the risks that remain, or begin, after a post-quantum "
            "migration. Completing a migration changes which of them apply; it "
            "does not empty this list."
        ),
    }
