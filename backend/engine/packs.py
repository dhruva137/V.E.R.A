# --------------------------------------------------------------------------
# Registry - the plug in / plug out surface
# --------------------------------------------------------------------------


class PackRegistry:
    """Which packs exist, and which are currently plugged in."""

    def __init__(self):
        # Baseline is always on. With every sector pack unplugged the product
        # must still be correct and useful, which is what agnostic actually
        # means - not "has no opinions" but "degrades to the universal ones".
        self._enabled: set[str] = {"pack.baseline"}

    def enable(self, pack_id: str) -> bool:
        if pack_id not in PACKS:
            return False
        self._enabled.add(pack_id)
        return True

    def disable(self, pack_id: str) -> bool:
        # Unplugging the floor is not a supported state: it would leave the
        # product with nothing to say rather than with less to say.
        if pack_id == "pack.baseline":
            return False
        self._enabled.discard(pack_id)
        return True

    def is_enabled(self, pack_id: str) -> bool:
        return pack_id in self._enabled

    def for_sector(self, sector: str) -> list[SectorPack]:
        """Enabled packs applying to a sector, most specific first."""
        matched = [
            p for p in PACKS.values()
            if p.sector == sector and self.is_enabled(p.id)
        ]
        baseline = PACKS["pack.baseline"]
        if self.is_enabled(baseline.id) and baseline not in matched:
            matched.append(baseline)
        return matched

    def describe(self) -> list[dict]:
        return [p.to_dict(self.is_enabled(p.id)) for p in PACKS.values()]

    def resolved(self, sector: str) -> dict:
        """Everything the product should say for this sector, merged.

        Sector packs take precedence and baseline fills the gaps, so unplugging
        a sector pack degrades the output to something still correct rather than
        to something empty. Duplicates are collapsed on identity, not on text,
        because two frameworks can word the same obligation differently and both
        need to appear.
        """
        packs = self.for_sector(sector)
        controls: list[dict] = []
        evidence: list[str] = []
        milestones: list[dict] = []
        questions: list[str] = []
        sources: list[str] = []
        framing = ""

        seen_controls: set[str] = set()
        seen_milestones: set[tuple] = set()

        for pack in packs:
            data = pack.to_dict(True)
            if not framing and data["board_framing"]:
                framing = data["board_framing"]
            for control in data["controls"]:
                if control["id"] not in seen_controls:
                    seen_controls.add(control["id"])
                    controls.append(control)
            for milestone in data["milestones"]:
                key = (milestone["year"], milestone["label"])
                if key not in seen_milestones:
                    seen_milestones.add(key)
                    milestones.append(milestone)
            for item in data["evidence"]:
                if item not in evidence:
                    evidence.append(item)
            for question in data["insurance_questions"]:
                if question not in questions:
                    questions.append(question)
            for source in data["sources"]:
                if source not in sources:
                    sources.append(source)

        milestones.sort(key=lambda m: m["year"])

        return {
            "sector": sector,
            "packs_applied": [p.id for p in packs],
            "board_framing": framing,
            "controls": controls,
            "evidence": evidence,
            "milestones": milestones,
            "insurance_questions": questions,
            "sources": sources,
            "note": (
                "Content supplied by sector packs. The engine's computation is "
                "identical for every sector; only what is said about the result "
                "changes."
            ),
        }


REGISTRY = PackRegistry()


def enable_all_sector_packs() -> None:
    """Default posture: every pack plugged in, so any sector is selectable."""
    for pack_id in PACKS:
        REGISTRY.enable(pack_id)


enable_all_sector_packs()


# --------------------------------------------------------------------------
# QIRS profile resolution data
#
# Adapters MUST set asset_class on every finding. These tables exist only for
# legacy assets that predate that requirement (source_type=config/source with
# no class). The branch lives in pack DATA, not in qirs if-statements.
# --------------------------------------------------------------------------

# Tag / custody / usage hint → profile key. Checked before source_type.
USAGE_OR_HINT_PROFILES: dict[str, str] = {
    "config": "config",
    "source": "source",
    "server_config": "config",
    "api_call": "source",
    "static_source": "source",
    "cipher_config": "config",
}

# Last-resort map for assets that only carried source_type. Do not add new
# entries here — set asset_class in the adapter instead.
LEGACY_SOURCE_TYPE_PROFILES: dict[str, str] = {
    "config": "config",
    "source": "source",
}


def resolve_qirs_profile_key(asset) -> str | None:
    """Legacy / hint path for QIRS profile selection.

    Returns a candidate profile key, or None when nothing matches. The caller
    (engine.qirs.resolve_profile) validates the key against PROFILES.

    Adapters MUST set asset_class. This helper exists for assets that only
    carried source_type=config/source (or tag/custody hints) with no class.
    """
    details = getattr(asset, "raw_details", None) or {}
    explicit = details.get("qirs_profile")
    if isinstance(explicit, str) and explicit:
        return explicit

    # Custody dict or free-form tags may carry a profile hint.
    custody = details.get("custody")
    hint_candidates: list[str] = []
    if isinstance(custody, dict):
        for key in ("kind", "type", "profile", "hint"):
            value = custody.get(key)
            if isinstance(value, str) and value:
                hint_candidates.append(value)
    elif isinstance(custody, str) and custody:
        hint_candidates.append(custody)

    for tag in getattr(asset, "tags", None) or []:
        if isinstance(tag, str) and tag:
            hint_candidates.append(tag)

    usage = getattr(asset, "usage", None)
    if isinstance(usage, str) and usage and usage != "key_exchange":
        hint_candidates.append(usage)

    for hint in hint_candidates:
        mapped = USAGE_OR_HINT_PROFILES.get(hint) or USAGE_OR_HINT_PROFILES.get(hint.lower())
        if mapped:
            return mapped
        # A tag that is already a profile key name.
        if hint in USAGE_OR_HINT_PROFILES.values() or hint in LEGACY_SOURCE_TYPE_PROFILES.values():
            return hint

    discovered = str(details.get("discovered_by") or "")
    discovered_l = discovered.lower()
    if "source" in discovered_l and "config" not in discovered_l:
        return "source"
    if "config" in discovered_l:
        return "config"

    # Last resort: legacy source_type table. Adapters must set asset_class.
    source_type = getattr(asset, "source_type", None) or ""
    return LEGACY_SOURCE_TYPE_PROFILES.get(source_type)
