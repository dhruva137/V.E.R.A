"""Sector packs - the plug-in / plug-out layer.

WHY THIS EXISTS
---------------
The engine must stay sector-agnostic: corroboration, scoring and the output
checks know nothing about payments or telecoms, and they must not, or every new
vertical becomes a branch inside the machine. But a payments processor and a grid
operator need genuinely different things - different regulators, different
evidence, different board language, different dates.

A **pack** is how that difference is supplied from outside the engine. It is
declarative content, not code: the controls a sector is audited against, the
evidence an auditor will ask for, the milestone calendar, the framing a board
memo opens with, and the questions an insurer now asks. Enabling a pack changes
what the product *says*; it never changes how the engine *computes*.

    engine core      agnostic, never edited per sector
      + sector pack  regulators, controls, evidence, dates, language
      + sensor pack  connectors (engine/plugins.py)
      = a product that fits one kind of organisation

Packs can be enabled and disabled at runtime. That is the point: agnosticism is
demonstrable rather than asserted, because a sector can be unplugged in front of
someone and the same estate is then judged by different rules.

CONTENT PROVENANCE
------------------
Every pack cites where its content came from - a published standard, a
regulator's document, a vendor's own release notes. Nothing here is inferred
from customer data and nothing is generated by a model. A control mapping that
cannot name its source is a liability in the one conversation it exists for.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class ComplianceControl:
    """A control this sector is audited against, and what answers it."""

    id: str
    framework: str
    requirement: str
    #: Which engine output constitutes evidence. This is the whole value: an
    #: auditor's question mapped to something the product already produces.
    answered_by: str


@dataclass(frozen=True)
class Milestone:
    """A dated obligation. Sourced, because a wrong date is worse than none."""

    year: int
    label: str
    source: str
    binding: bool = False


@dataclass(frozen=True)
class SectorPack:
    """Declarative content that specialises the agnostic engine."""

    id: str
    name: str
    version: str
    sector: str
    summary: str
    controls: list[ComplianceControl] = field(default_factory=list)
    evidence: list[str] = field(default_factory=list)
    milestones: list[Milestone] = field(default_factory=list)
    board_framing: str = ""
    insurance_questions: list[str] = field(default_factory=list)
    sources: list[str] = field(default_factory=list)

    def to_dict(self, enabled: bool) -> dict:
        return {
            "id": self.id,
            "name": self.name,
            "version": self.version,
            "sector": self.sector,
            "summary": self.summary,
            "enabled": enabled,
            "controls": [
                {
                    "id": c.id, "framework": c.framework,
                    "requirement": c.requirement, "answered_by": c.answered_by,
                }
                for c in self.controls
            ],
            "evidence": list(self.evidence),
            "milestones": [
                {"year": m.year, "label": m.label, "source": m.source,
                 "binding": m.binding}
                for m in sorted(self.milestones, key=lambda m: m.year)
            ],
            "board_framing": self.board_framing,
            "insurance_questions": list(self.insurance_questions),
            "sources": list(self.sources),
            "counts": {
                "controls": len(self.controls),
                "milestones": len(self.milestones),
                "binding_milestones": sum(1 for m in self.milestones if m.binding),
            },
        }


PACKS: dict[str, SectorPack] = {}


def _register(pack: SectorPack) -> SectorPack:
    PACKS[pack.id] = pack
    return pack


